def multiplicacao (x, y): 
    resultado = x * y
    return resultado
def soma (x , y):
    resultado = x + y
    return resultado
def divisao (x , y):
    resultado = x / y
    return resultado
def menos (x, y):
    resultado = x - y
    return resultado

